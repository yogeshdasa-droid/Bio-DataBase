export function formatDate(d: string | null, lang: Lang): string {
  if (!d) return "";
  const [y, m, day] = d.split("-").map(Number);
  const locale = lang === "es" ? "es-ES" : "en-GB";
  if (day) return new Date(y, m - 1, day).toLocaleDateString(locale, { day: "numeric", month: "short", year: "numeric" });
  if (m) return new Date(y, m - 1, 1).toLocaleDateString(locale, { month: "short", year: "numeric" });
  return String(y);
}

export function formatSize(chars: number, lang: Lang): string {
  if (chars < 1024) return `${chars.toLocaleString(lang)} B`;
  return `${Math.round(chars / 1024).toLocaleString(lang)} KB`;
}
